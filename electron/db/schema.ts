import type Database from 'better-sqlite3';
export function migrate(db: Database.Database) {
 db.exec(`
 PRAGMA foreign_keys=ON;
 CREATE TABLE IF NOT EXISTS products(
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, category TEXT NOT NULL,
  type TEXT NOT NULL CHECK(type IN ('Stock','Service')), cost REAL NOT NULL DEFAULT 0,
  retail REAL NOT NULL DEFAULT 0, wholesale REAL NOT NULL DEFAULT 0,
  stock INTEGER NOT NULL DEFAULT 0, sku TEXT UNIQUE, active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
 );
 CREATE TABLE IF NOT EXISTS customers(
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, phone TEXT, address TEXT,
  opening_balance REAL NOT NULL DEFAULT 0, balance REAL NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
 );
 CREATE TABLE IF NOT EXISTS sales(
  id INTEGER PRIMARY KEY AUTOINCREMENT, invoice TEXT NOT NULL UNIQUE, customer_id INTEGER REFERENCES customers(id),
  customer_name TEXT NOT NULL DEFAULT 'Walk-in Customer', subtotal REAL NOT NULL, discount REAL NOT NULL DEFAULT 0,
  total REAL NOT NULL, paid REAL NOT NULL DEFAULT 0, due REAL NOT NULL DEFAULT 0,
  payment_method TEXT NOT NULL DEFAULT 'Cash', sale_type TEXT NOT NULL DEFAULT 'Retail',
  status TEXT NOT NULL DEFAULT 'Completed', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
 );
 CREATE TABLE IF NOT EXISTS sale_items(
  id INTEGER PRIMARY KEY AUTOINCREMENT, sale_id INTEGER NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
  product_id INTEGER REFERENCES products(id), name TEXT NOT NULL, qty INTEGER NOT NULL,
  price REAL NOT NULL, cost REAL NOT NULL, type TEXT NOT NULL
 );
 CREATE TABLE IF NOT EXISTS payments(
  id INTEGER PRIMARY KEY AUTOINCREMENT, sale_id INTEGER REFERENCES sales(id), customer_id INTEGER REFERENCES customers(id),
  amount REAL NOT NULL, method TEXT NOT NULL DEFAULT 'Cash', note TEXT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
 );
 CREATE TABLE IF NOT EXISTS expenses(id INTEGER PRIMARY KEY AUTOINCREMENT,title TEXT NOT NULL,amount REAL NOT NULL,category TEXT,created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
 CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS stock_movements(id INTEGER PRIMARY KEY AUTOINCREMENT,product_id INTEGER REFERENCES products(id),qty_change INTEGER NOT NULL,reason TEXT NOT NULL,ref_id INTEGER,created_at TEXT DEFAULT CURRENT_TIMESTAMP);
 CREATE INDEX IF NOT EXISTS idx_sales_date ON sales(created_at);
 CREATE INDEX IF NOT EXISTS idx_sale_items_sale ON sale_items(sale_id);
 CREATE INDEX IF NOT EXISTS idx_products_name ON products(name);
 `);
}
